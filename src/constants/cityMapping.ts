export const getClosestCity = (lat: number, lng: number): string | null => {
  let closestCity: string | null = null;
  let minDistance = Infinity;

  const R = 6371; // km
  for (const [city, coords] of Object.entries(cityCoords)) {
    const dLat = (coords.lat - lat) * Math.PI / 180;
    const dLon = (coords.lng - lng) * Math.PI / 180;
    const a = 
      Math.sin(dLat/2) * Math.sin(dLat/2) +
      Math.cos(lat * Math.PI / 180) * Math.cos(coords.lat * Math.PI / 180) * 
      Math.sin(dLon/2) * Math.sin(dLon/2);
    const c = 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1-a));
    const distance = R * c;

    if (distance < minDistance) {
      minDistance = distance;
      closestCity = city;
    }
  }

  // Only return the city if it's within a reasonable radius (e.g., 50km)
  return minDistance <= 50 ? closestCity : null;
};

export const getDisplayCity = (listing: any): string => {
  // Try to use coordinates to find the real city, especially if it fell back to 'سطات'
  if (listing.coordinates && listing.coordinates.lat && listing.coordinates.lng) {
    if (!listing.location || listing.location === 'سطات' || listing.location === 'موقع على الخريطة') {
      const closest = getClosestCity(listing.coordinates.lat, listing.coordinates.lng);
      if (closest) return closest;
    }
  }
  
  // Try fallback string logic
  const rawLocation = listing.city || listing.location || '';
  return cityMapping[rawLocation.toLowerCase()] || rawLocation || 'غير محدد';
};
