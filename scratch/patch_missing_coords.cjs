// ─── Parse current cityCoords ────────────────────────────────────────────────
const coordsMatch = raw.match(/export const cityCoords[^=]+=\s*(\{[\s\S]+?\});\s*\n/);
if (!coordsMatch) { console.error('Cannot parse cityCoords block'); process.exit(1); }
const currentCoords = JSON.parse(coordsMatch[1].replace(/,\s*\n(\s*})/g, '\n$1'));

// Merge patches
let added = 0;
for (const [arName, coords] of Object.entries(PATCH)) {
  if (!currentCoords[arName]) {
    currentCoords[arName] = coords;
    added++;
  }
}
console.log(`Patched ${added} new coordinates`);
console.log(`Total cityCoords entries: ${Object.keys(currentCoords).length}`);

// Sort
const sorted = {};
Object.keys(currentCoords).sort().forEach(k => { sorted[k] = currentCoords[k]; });

// Replace the cityCoords block in the file
const newCoordsBlock = `export const cityCoords: { [key: string]: { lat: number; lng: number } } = ${JSON.stringify(sorted, null, 2)};`;
const updated = raw.replace(
  /export const cityCoords[^=]+=\s*\{[\s\S]+?\};/,
  newCoordsBlock
);

fs.writeFileSync(outPath, updated, 'utf8');
console.log(`✅ Patched and written to: ${outPath}`);
console.log(`   File size: ${(fs.statSync(outPath).size / 1024).toFixed(1)} KB`);
